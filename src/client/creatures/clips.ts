export function fidgets(...names: FidgetName[]): Clip[] {
  return names.map((n) => FIDGETS[n]);
}

/** A copy of `c` with extra (or replaced) tracks. */
export function withTracks(c: Clip, extra: Partial<Record<Channel, Keys>>): Clip {
  const tracks = c.tracks.filter(([ch]) => !(Object.keys(extra) as Channel[]).some((k) => CH[k] === ch));
  for (const k of Object.keys(extra) as Channel[]) tracks.push([CH[k], extra[k]!]);
  return { dur: c.dur, hold: c.hold, tracks };
}

/** Bird actions: the quadruped set plus wing beats (pecks, a wing-spread special, flinches). */
