/**
 * Hand-keyed one-shot actions and idle fidgets. Values are additive offsets on the pose
 * channels (translations in units of the creature's height S, angles in radians); keys are
 * [time s, value] with auto-clamped tangents, so every key is an eased extreme.
 */

export interface ClipParams {
  /** Y offset (in S) that puts the body on the ground when rolled onto its side. */
  lieY: number;
  /** Roll when fainted (about pi/2 = on its side, about pi = on its back). */
  faintRoll: number;
  /** Lunge distance (in S). */
  lunge: number;
  /** Rear-up angle for the special. */
  rear: number;
  /** Happy hop height (in S). */
  hop: number;
}

