import type { LearnEntry, SpeciesData, StatTable } from '../battle/types';

/**
 * The rest of Kanto's Pokémon, for Sijord's wider region (2026-10-11): every species whose model
 * in the catalogue walks. Canonical types, base stats, growth rates, base experience, effort
 * yields, catch rates and heights; level-up learnsets keep the moves the engine has.
 *
 * Evolutions by stone or by trade have no item or trade in Sijord yet, so they use a stand-in
 * level (the same rule species.ts uses for Pikachu, Clefairy and Growlithe): Nidorina and Nidorino
 * at 36, Vulpix 32, Jigglypuff 30, Gloom 32, Poliwhirl 36, Kadabra 36, Machoke 40, Weepinbell 34,
 * Graveler 40, Shellder 36, Haunter 40, Exeggcute 34, Staryu 34.
 *
 * Abilities are ones the engine models, plus three it lists without an effect yet (Sand Veil,
 * Swift Swim and Oblivious) for species that have nothing else. Descriptions are original.
 */
type Entry = Omit<SpeciesData, 'name' | 'dex'>;

function learn(...entries: [number, string][]): LearnEntry[] {
  return entries.map(([level, move]) => ({ level, move }));
}

function stats(hp: number, atk: number, def: number, spa: number, spd: number, spe: number): StatTable {
  return { hp, atk, def, spa, spd, spe };
}

